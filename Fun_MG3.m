%% 风险值计算函数
function [VaR3, CVaR3, F_loss_total] = calculateRiskMetrics3(Z, T, N_w, beta, lambda_loss3_t, P_loss3, rho)
    % 置信水平
    alpha3 = 0.95;  % 可以改为输入参数，这里固定为0.95
    
    % 计算每个场景下每个用户的损失费用
    F_i_loss_t = zeros(Z, T, N_w);  % 时刻损失矩阵
    F_i_loss_k = zeros(Z, N_w);     % 用户场景总损失矩阵
    
    for i = 1:Z
        for t = 1:T
            for k = 1:N_w
                % 计算t时刻用户i在场景k的损失费用
                F_i_loss_t(i, t, k) = lambda_loss3_t(t) * P_loss3(i, t, k);
            end
        end
        
        % 计算用户i在各场景的总损失（时间维度求和）
        for k = 1:N_w
            F_i_loss_k(i, k) = sum(F_i_loss_t(i, :, k));
        end
    end
    
    % 计算调度时段总损失费用（期望值）
    F_loss_total = 0;
    for i = 1:Z
        for t = 1:T
            F_loss_total = F_loss_total + mean(squeeze(F_i_loss_t(i, t, :)));
        end
    end
    
    % 计算每个用户的VaR3
    VaR3 = zeros(Z, 1);  % 初始化VaR3向量
    
    for i = 1:Z
        % 获取当前用户在所有场景下的损失值
        user_losses = squeeze(F_i_loss_k(i, :));
        
        % 按损失值升序排序
        [sorted_losses, sort_idx] = sort(user_losses);
        
        % 计算累积概率分布
        cum_prob = cumsum(rho(sort_idx));
        
        % 找到满足累积概率 ≥ alpha3 的最小损失值（VaR3定义）
        idx = find(cum_prob >= alpha3, 1, 'first');
        
        if isempty(idx)
            VaR3(i) = sorted_losses(end);  % 若未找到则取最大值
        else
            VaR3(i) = sorted_losses(idx);
        end
    end
    
    % 计算每个用户的CVaR3 - 使用标准公式
    CVaR3 = zeros(Z, 1);  % 初始化CVaR3向量
    
    for i = 1:Z
        user_losses = squeeze(F_i_loss_k(i, :));
        
        % 找到超过VaR3的损失
        exceed_idx = user_losses > VaR3(i);
        
        if any(exceed_idx)
            % 计算超过VaR3的损失的条件期望
            exceed_values = user_losses(exceed_idx);
            exceed_probs = rho(exceed_idx) / sum(rho(exceed_idx));
            conditional_expectation = sum(exceed_values .* exceed_probs);
            CVaR3(i) = conditional_expectation;
        else
            % 如果没有超过VaR3的损失，则CVaR3 = VaR3
            CVaR3(i) = VaR3(i);
        end
    end
    
    % 或者使用标准CVaR公式
    % CVaR_alpha = VaR_alpha + 1/(1-alpha) * E[max(L - VaR_alpha, 0)]
    for i = 1:Z
        user_losses = squeeze(F_i_loss_k(i, :));
        
        % 计算超出VaR的损失部分
        excess = max(user_losses - VaR3(i), 0);
        
        % 计算excess的期望值
        expected_excess = sum(rho .* excess);
        
        % 计算CVaR
        CVaR3(i) = VaR3(i) + (1/(1 - alpha3)) * expected_excess;
    end
end


